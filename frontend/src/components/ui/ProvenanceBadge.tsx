import React from 'react';
import { Compass, Cpu, Eye, Globe, Sliders } from 'lucide-react';
import type { EpistemicType } from '../../types/api';

interface ProvenanceConfig {
  label: string;
  description: string;
  bgVar: string;
  textVar: string;
  borderVar: string;
  Icon: React.ComponentType<{ className?: string }>;
}

const PROVENANCE_MAP: Record<EpistemicType, ProvenanceConfig> = {
  observed: {
    label: 'Observed',
    description: 'Directly recorded field observation, scout measurement, or sensor readout.',
    bgVar: 'var(--prov-observed-bg)',
    textVar: 'var(--prov-observed-text)',
    borderVar: 'var(--prov-observed-border)',
    Icon: Eye,
  },
  external: {
    label: 'External',
    description: 'Sourced from external agroclimatology or satellite provider (e.g., NASA POWER).',
    bgVar: 'var(--prov-external-bg)',
    textVar: 'var(--prov-external-text)',
    borderVar: 'var(--prov-external-border)',
    Icon: Globe,
  },
  predicted: {
    label: 'Predicted',
    description: 'Output generated by a trained machine learning or computer vision model.',
    bgVar: 'var(--prov-predicted-bg)',
    textVar: 'var(--prov-predicted-text)',
    borderVar: 'var(--prov-predicted-border)',
    Icon: Cpu,
  },
  simulated: {
    label: 'Simulated',
    description: 'Projected by a mathematical scenario engine or agricultural digital twin.',
    bgVar: 'var(--prov-simulated-bg)',
    textVar: 'var(--prov-simulated-text)',
    borderVar: 'var(--prov-simulated-border)',
    Icon: Sliders,
  },
  recommended: {
    label: 'Recommended',
    description: 'Prescriptive advisory generated by the agronomic rule engine.',
    bgVar: 'var(--prov-recommended-bg)',
    textVar: 'var(--prov-recommended-text)',
    borderVar: 'var(--prov-recommended-border)',
    Icon: Compass,
  },
};

interface ProvenanceBadgeProps {
  type: EpistemicType | string;
  size?: 'sm' | 'md';
  showTooltipText?: boolean;
  className?: string;
}

export const ProvenanceBadge: React.FC<ProvenanceBadgeProps> = ({
  type,
  size = 'sm',
  className = '',
}) => {
  const normalized = (type || 'observed').toLowerCase() as EpistemicType;
  const config = PROVENANCE_MAP[normalized] || PROVENANCE_MAP.observed;
  const { Icon } = config;

  return (
    <span
      role="status"
      aria-label={`Data Provenance: ${config.label} — ${config.description}`}
      title={`${config.label.toUpperCase()}: ${config.description}`}
      style={{
        backgroundColor: config.bgVar,
        color: config.textVar,
        borderColor: config.borderVar,
      }}
      className={`inline-flex items-center gap-1.5 font-semibold uppercase tracking-wider border rounded-full select-none ${
        size === 'sm' ? 'px-2.5 py-0.5 text-[11px]' : 'px-3 py-1 text-xs'
      } ${className}`}
    >
      <Icon className={size === 'sm' ? 'w-3 h-3 shrink-0' : 'w-3.5 h-3.5 shrink-0'} />
      <span>{config.label}</span>
    </span>
  );
};
